#!/usr/bin/env python3
# ABOUTME: Reshape the explorer sidecar JSONs under docs/api/ into tidy, queryable tables
# ABOUTME: for publication to Hugging Face — one row per observation, facets as columns.
"""build_capability_datasets.py — tidy datasets for the capability-promotion wave.

    uv run python scripts/hf/build_capability_datasets.py [--out DIR]

Why this exists
---------------
The `*.json` sidecars next to each explorer page are shaped for the PAGE: facet trees
for dropdowns, square matrices for heatmaps. That is the right shape for the UI and the
wrong shape for a dataset — a generic publisher turns
`series -> structure -> climate -> coating -> [rows]` into sixteen 7-row tables, and a
16x16 verdict matrix into one cell of stringified JSON.

This module holds the knowledge the publisher cannot infer: which nesting levels are
facets (and so become columns) and what a matrix is indexed by. Output is tidy — one row
per observation — so `save_results_to_hf.py` publishes it without any discovery cleverness.

Provenance: reads only the committed sidecars, which are themselves generated by
scripts/capabilities/build_*.py and scripts/corrosion/build_*.py. So the chain from
calculation to published dataset is repo code end to end, and re-running this after a
generator re-run reproduces the dataset exactly (aceengineer-website#97, #1646).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
_API = _REPO / "docs" / "api"


def _load(rel: str) -> dict:
    return json.loads((_API / rel).read_text(encoding="utf-8"))


def wall_thickness_rows() -> list[dict]:
    """series[standard] -> rows. The standard becomes a column, so all six codes are
    comparable in one query instead of six sibling tables."""
    doc = _load("structural/wall-thickness-explorer.json")
    meta = doc.get("meta", {})
    out: list[dict] = []
    for standard, rows in doc["series"].items():
        for r in rows:
            row = {
                "standard": standard,
                "wall_thickness_mm": r["w"],
                "utilisation": r["u"],
                "governing_check": r.get("g"),
                "safe": r.get("safe"),
            }
            # per-check utilisations vary by standard; keep them as explicit columns
            for check, val in (r.get("checks") or {}).items():
                row[f"check_{check}"] = val
            row["od_mm"] = meta.get("od_mm")
            row["grade"] = meta.get("grade")
            out.append(row)
    return out


def cathodic_protection_rows() -> list[dict]:
    """series[structure][climate][coating] -> rows. Three facet levels become three
    columns; 16 sibling tables become one queryable table."""
    doc = _load("structural/cathodic-protection-explorer.json")
    out: list[dict] = []
    for structure, by_climate in doc["series"].items():
        for climate, by_coating in by_climate.items():
            for coating, rows in by_coating.items():
                for r in rows:
                    out.append({
                        "structure": structure,
                        "climate": climate,
                        "coating": coating,
                        "design_life_years": r["l"],
                        "anode_mass_kg": r["mass"],
                        "anode_count": r["n"],
                        "current_mean_a": r.get("im"),
                        "current_final_a": r.get("if"),
                    })
    return out


def wall_thickness_3d_rows() -> list[dict]:
    """The (t, T, M) study from build_wall_thickness_3d.py — already tidy, so this only
    reads it. 354,609 rows: 191 MB as JSON, ~1 MB as parquet, which is why the JSON is
    gitignored and only the published dataset is durable (#1915)."""
    doc = _load("structural/wall-thickness-3d.json")
    return doc["rows"]


def galvanic_rows() -> list[dict]:
    """environments[env] holds 16x16 matrices indexed by the `metals` list. Unpivot to one
    row per (environment, metal pair) — 16 x 16 x 3 = 768 rows."""
    doc = _load("corrosion/galvanic-compatibility-explorer.json")
    metals = doc["metals"]
    labels = doc.get("labels") or metals
    index_v = doc.get("anodic_index_v") or []
    out: list[dict] = []
    for env_key, env in doc["environments"].items():
        verdict = env.get("verdict") or []
        rank = env.get("rank") or []
        delta = env.get("delta_v") or []
        anodic = env.get("anodic") or []
        for i, a in enumerate(metals):
            for j, b in enumerate(metals):
                out.append({
                    "environment": env_key,
                    "environment_label": env.get("label"),
                    "allowable_delta_v": env.get("allowable_v"),
                    "metal_a": a,
                    "metal_a_label": labels[i] if i < len(labels) else a,
                    "metal_a_anodic_index_v": index_v[i] if i < len(index_v) else None,
                    "metal_b": b,
                    "metal_b_label": labels[j] if j < len(labels) else b,
                    "metal_b_anodic_index_v": index_v[j] if j < len(index_v) else None,
                    "verdict": verdict[i][j] if i < len(verdict) and j < len(verdict[i]) else None,
                    "rank": rank[i][j] if i < len(rank) and j < len(rank[i]) else None,
                    "delta_v": delta[i][j] if i < len(delta) and j < len(delta[i]) else None,
                    "anodic_member": anodic[i][j] if i < len(anodic) and j < len(anodic[i]) else None,
                })
    return out


#: dataset id -> {table name: builder}. Grouped per the epic's decision 1 — one dataset
#: per coherent projection, several capabilities to a dataset.
DATASETS = {
    "digitalmodel-integrity": {
        "wall_thickness": wall_thickness_rows,
        "wall_thickness_tension_moment": wall_thickness_3d_rows,
    },
    "digitalmodel-corrosion": {
        "cathodic_protection": cathodic_protection_rows,
        "galvanic_compatibility": galvanic_rows,
    },
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(_REPO / "docs" / "api" / "_datasets"),
                    help="directory to write <dataset>/<table>.json into")
    args = ap.parse_args()
    out_root = Path(args.out)

    for dataset, tables in DATASETS.items():
        d = out_root / dataset
        d.mkdir(parents=True, exist_ok=True)
        for name, fn in tables.items():
            rows = fn()
            (d / f"{name}.json").write_text(
                json.dumps(rows, indent=1) + "\n", encoding="utf-8")
            cols = len(rows[0]) if rows else 0
            print(f"{dataset}/{name}.json: {len(rows)} rows x {cols} cols")


if __name__ == "__main__":
    main()
