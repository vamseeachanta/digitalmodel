#!/usr/bin/env python3
"""Generate tests/OWNERS.toml: which test files cover each source unit.

The fast gate (``scripts/ci/fast_gate.py``) reads the file to pick the test
files a change needs. Nothing in it is written by hand:

* ``[shards]`` lists the test files each domain gate selects, resolved from
  ``.claude/quality-gates.yaml`` and the workflow's gate reader by the same code
  as the test-selection audit (``scripts/ci/orphan_tests.py``).
* ``[sources]`` maps each source unit to the test files that import it,
  directly or through other source modules, test helper modules or conftest
  files. A unit is a top-level module (``src/digitalmodel/x.py``), a package
  folder (``src/digitalmodel/x/``) or a folder one level below a package
  (``src/digitalmodel/x/y/``), the same units as the detector's source routes.
  Every import in a test file counts. In a source file only the imports that
  run when the module is loaded count, not those inside functions: counting
  those made almost every unit reach almost every test through dispatchers
  such as ``digitalmodel.engine``. Importing a module runs its parent packages'
  ``__init__`` files, so those count too. A string naming a module
  (``"digitalmodel.x.y"``) or a source path (``"src/digitalmodel/x/"``) in a
  test also counts, for tests that import by name or run a module as a command.

What static imports cannot see (a test reaching a module only through a
function-level import or a configuration-driven dispatch) is what the shadow
run measures: such a miss shows up as a fast-gate pass beside a matrix failure.

Run with ``--check`` to fail when the committed file differs from a fresh
generation.
"""

from __future__ import annotations

import argparse
import ast
from collections import defaultdict
import difflib
from pathlib import Path
import re
import sys
import warnings

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path("tests/OWNERS.toml")
SOURCE = Path("src")
PACKAGE = "digitalmodel"
WORKFLOW = Path(".github/workflows/quality-gates-by-domain.yml")
MODULE_NAME = re.compile(r"\bdigitalmodel(?:\.[A-Za-z_]\w*)+")
SOURCE_PATH = re.compile(r"\bsrc/digitalmodel/[\w./-]*")
HEADER = """\
# Generated by scripts/ci/generate_owners.py. Do not edit by hand.
# Regenerate:  python scripts/ci/generate_owners.py
# Check:       python scripts/ci/generate_owners.py --check
#
# [shards.<domain>] tests: the test files the domain gate selects.
# [sources."<unit>"] the test files that import the unit, directly or through
#   other modules. An entry ending in "/" stands for every test file of the
#   [shards] lists under that folder.
"""


def module_files(root: Path) -> dict[str, Path]:
    """Map every importable digitalmodel module name to its file."""
    modules = {}
    base = root / SOURCE
    for path in sorted((base / PACKAGE).rglob("*.py")):
        parts = list(path.relative_to(base).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        if all(part.isidentifier() for part in parts):
            modules[".".join(parts)] = path
    return modules


def unit_of(relative: str) -> str | None:
    """The source unit holding a repository-relative path under src/digitalmodel."""
    parts = relative.split("/")
    if parts[:2] != ["src", PACKAGE] or len(parts) < 3:
        return None
    if len(parts) == 3:
        return relative  # a top-level module or file
    if len(parts) == 4:
        return "/".join(parts[:3]) + "/"
    return "/".join(parts[:4]) + "/"


def parents(module: str) -> list[str]:
    pieces = module.split(".")
    return [".".join(pieces[:index]) for index in range(1, len(pieces))]


def resolve(name: str, modules: dict[str, Path]) -> str | None:
    """The longest importable prefix of a dotted name."""
    pieces = name.split(".")
    for end in range(len(pieces), 0, -1):
        candidate = ".".join(pieces[:end])
        if candidate in modules:
            return candidate
    return None


def module_level(tree: ast.AST):
    """Walk a module without entering function bodies: what importing it runs."""
    pending = [tree]
    while pending:
        node = pending.pop()
        yield node
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            pending.extend(ast.iter_child_nodes(node))


def imported_names(path: Path, package: str | None, load_only: bool = False) -> tuple[set[str], set[str]]:
    """Absolute dotted names a file imports, and module-looking names in its strings.

    With ``load_only``, imports inside functions are left out: they run when the
    function is called, not when the module is imported."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            tree = ast.parse(path.read_bytes(), filename=str(path))
    except (SyntaxError, ValueError):
        return set(), set()
    names: set[str] = set()
    strings: set[str] = set()
    for node in (module_level(tree) if load_only else ast.walk(tree)):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                if not package:
                    continue
                anchor = package.split(".")
                anchor = anchor[:len(anchor) - node.level + 1]
                base = ".".join(anchor + ([node.module] if node.module else []))
            else:
                base = node.module or ""
            names.add(base)
            names.update(f"{base}.{alias.name}" for alias in node.names if alias.name != "*")
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            strings.add(node.value)
    return names, strings


def string_references(strings: set[str], modules: dict[str, Path], root: Path) -> set[str]:
    """Modules named in string constants, by dotted name or by source path."""
    found = set()
    for text in strings:
        for match in MODULE_NAME.findall(text):
            if (module := resolve(match, modules)) and module != PACKAGE:
                found.add(module)
        for match in SOURCE_PATH.findall(text):
            target = match.rstrip("/.")
            path = root / target
            for candidate in (path, path.with_suffix(".py"), path / "__init__.py"):
                if candidate.is_file() and candidate.suffix == ".py":
                    name = ".".join(candidate.relative_to(root / SOURCE).with_suffix("").parts)
                    found.add(name.removesuffix(".__init__"))
                    break
            else:
                if unit := unit_of(target if not path.is_dir() else target + "/"):
                    found.add("unit:" + unit)
    return found


def gate_extras(command: str) -> list[str]:
    """Optional dependency groups a gate command installs (``.[test,fowt]``, ``--extra cfd``)."""
    extras = set()
    for group in re.findall(r"\.\[([\w,-]+)\]", command):
        extras.update(group.split(","))
    extras.update(re.findall(r"--extra[ =]([\w-]+)", command))
    return sorted(extras)


def shard_tests(root: Path) -> dict[str, tuple[list[str], list[str]]]:
    """The test files each domain gate selects, as the test-selection audit resolves
    them, and the optional dependency groups the gate installs."""
    sys.path.insert(0, str(root / "scripts/ci"))
    try:
        import orphan_tests
    finally:
        sys.path.remove(str(root / "scripts/ci"))
    files, ignored = orphan_tests.candidates(root)
    text = (root / WORKFLOW).read_text(encoding="utf-8")
    return {
        domain: (sorted(orphan_tests.selected_paths(command, files, ignored, root)), gate_extras(command))
        for domain, command in orphan_tests.domain_commands(root, text)
    }


def generate(root: Path = ROOT) -> str:
    modules = module_files(root)
    module_units = {name: unit_of(path.relative_to(root).as_posix()) for name, path in modules.items()}
    graph: dict[str, set[str]] = {}
    for name, path in modules.items():
        package = name if path.name == "__init__.py" else name.rpartition(".")[0]
        imported, _ = imported_names(path, package, load_only=True)
        targets = {resolve(item, modules) for item in imported if item.startswith(PACKAGE)}
        graph[name] = {target for target in targets if target}

    def closure(start: set[str]) -> set[str]:
        seen: set[str] = set()
        pending = list(start)
        while pending:
            module = pending.pop()
            if module in seen:
                continue
            seen.add(module)
            # Importing a module runs every parent package's __init__ first.
            pending.extend(parents(module))
            pending.extend(graph.get(module, ()))
        return seen

    gates = shard_tests(root)
    shards = {domain: tests for domain, (tests, _) in gates.items()}
    tests_root = root / "tests"
    helper_cache: dict[tuple[Path, bool], tuple[set[str], set[str]]] = {}

    def direct(path: Path, use_strings: bool = True) -> tuple[set[str], set[str]]:
        """Modules and units a test-side file reaches, following test helper imports.

        Strings in conftest files are not read: there they name modules to stub
        (``sys.modules[...]``), which loads nothing."""
        key = (path, use_strings)
        if key in helper_cache:
            return helper_cache[key]
        helper_cache[key] = (set(), set())  # cycle guard
        package = ".".join(path.relative_to(root).with_suffix("").parts[:-1])
        imported, strings = imported_names(path, package)
        found_modules, found_units = set(), set()
        for item in imported:
            if item.startswith(PACKAGE + ".") or item == PACKAGE:
                if module := resolve(item, modules):
                    found_modules.add(module)
            elif item.startswith("tests."):
                target = root / Path(*item.split("."))
                for candidate in (target.with_suffix(".py"), target / "__init__.py"):
                    if candidate.is_file():
                        more_modules, more_units = direct(candidate)
                        found_modules = found_modules | more_modules
                        found_units = found_units | more_units
                        break
        for reference in string_references(strings, modules, root) if use_strings else ():
            if reference.startswith("unit:"):
                found_units.add(reference[5:])
            else:
                found_modules.add(reference)
        helper_cache[key] = (found_modules, found_units)
        return helper_cache[key]

    owners: dict[str, set[str]] = defaultdict(set)
    for test in sorted({test for tests in shards.values() for test in tests}):
        path = root / test
        reached_modules, reached_units = (set(found) for found in direct(path))
        # conftest files above the test load with it.
        folder = path.parent
        while True:
            conftest = folder / "conftest.py"
            if conftest.is_file():
                more_modules, more_units = direct(conftest, use_strings=False)
                reached_modules |= more_modules
                reached_units |= more_units
            if folder in (tests_root, root):
                break
            folder = folder.parent
        for module in closure(reached_modules):
            if unit := module_units.get(module):
                owners[unit].add(test)
        for unit in reached_units:
            owners[unit].add(test)

    lines = [HEADER, "version = 1", ""]
    for domain in sorted(shards):
        lines.append(f'[shards.{domain}]')
        lines.append(array("tests", shards[domain]))
        lines.append(array("extras", gates[domain][1]))
        lines.append("")
    universe = {test for tests in shards.values() for test in tests}
    for unit in sorted(owners):
        lines.append(f'[sources."{unit}"]')
        lines.append(array("tests", compress(owners[unit], universe)))
        lines.append("")
    return "\n".join(lines)


def folders_of(test: str) -> list[str]:
    parts = test.split("/")[:-1]
    return ["/".join(parts[:end]) + "/" for end in range(2, len(parts) + 1)]


def compress(tests: set[str], universe: set[str]) -> list[str]:
    """Replace every test file under a folder by the folder ("tests/x/") when the
    set holds all of that folder's gate-selected test files."""
    members: dict[str, set[str]] = defaultdict(set)
    for test in universe:
        for folder in folders_of(test):
            members[folder].add(test)
    chosen: list[str] = []
    covered: set[str] = set()
    for folder in sorted(members, key=lambda item: (item.count("/"), item)):
        if any(folder.startswith(parent) for parent in chosen):
            continue
        if members[folder] <= tests:
            chosen.append(folder)
            covered |= members[folder]
    return sorted(chosen + sorted(tests - covered))


def expand(entries: list[str], universe: set[str]) -> set[str]:
    """Inverse of compress: folders stand for their gate-selected test files."""
    result = set()
    for entry in entries:
        if entry.endswith("/"):
            result.update(test for test in universe if test.startswith(entry))
        else:
            result.add(entry)
    return result


def array(key: str, values: list[str]) -> str:
    if not values:
        return f"{key} = []"
    body = "".join(f'  "{value}",\n' for value in values)
    return f"{key} = [\n{body}]"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, help="write here instead of tests/OWNERS.toml")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    text = generate(root)
    target = args.output or root / OUTPUT
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current == text:
            print(f"{OUTPUT} is current.")
            return 0
        diff = list(difflib.unified_diff(current.splitlines(), text.splitlines(),
                                         str(OUTPUT), "generated", lineterm="", n=0))
        print("\n".join(diff[:60]))
        print(f"{OUTPUT} is stale: run python scripts/ci/generate_owners.py", file=sys.stderr)
        return 1
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
