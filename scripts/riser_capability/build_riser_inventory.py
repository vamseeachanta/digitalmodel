"""Render the riser capability inventory from data/riser_capability/riser_types.yml.

Usage (from the repository root):
    python scripts/riser_capability/build_riser_inventory.py          # write
    python scripts/riser_capability/build_riser_inventory.py --check  # verify

Record counts are computed from the data files; none is typed by hand.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data" / "riser_capability" / "riser_types.yml"
OUTPUT = ROOT / "docs" / "domains" / "risers" / "riser-capability-inventory.md"
STATUSES = ("static_screen", "components_only", "absent")
STATUS_TEXT = {
    "static_screen": "open-source static screen with tests",
    "components_only": "calculation parts only; no configuration solver",
    "absent": "no calculation in the repository",
}
PATH_KEYS = ("modules", "tests", "example_inputs", "public_solver_examples", "worked_configurations")


def load_inventory(path: Path = SOURCE) -> dict:
    """Load and validate the inventory; raise ValueError on any defect."""
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    database_ids = [row["id"] for row in data["databases"]]
    if len(set(database_ids)) != len(database_ids):
        raise ValueError("database ids must be unique")
    seen = set()
    for entry in data["riser_types"]:
        name = entry["id"]
        if name in seen:
            raise ValueError(f"duplicate riser type {name}")
        seen.add(name)
        if entry["status"] not in STATUSES:
            raise ValueError(f"{name}: unknown status {entry['status']}")
        if entry["status"] == "absent" and (entry["modules"] or entry["worked_configurations"]):
            raise ValueError(f"{name}: an absent capability lists modules or worked cases")
        if entry["status"] != "absent" and not (entry["modules"] and entry["tests"]):
            raise ValueError(f"{name}: a stated capability needs modules and tests")
        if not entry["not_established"].strip():
            raise ValueError(f"{name}: not_established must name the missing evidence")
        for key in PATH_KEYS:
            for item in entry[key]:
                if not (ROOT / item).exists():
                    raise ValueError(f"{name}: {key} path does not exist: {item}")
        for item in entry["databases"]:
            if item not in database_ids:
                raise ValueError(f"{name}: unknown database {item}")
    for row in data["databases"]:
        if not (ROOT / row["path"]).exists():
            raise ValueError(f"database path does not exist: {row['path']}")
    for item in data["excluded_model_folders"]["paths"]:
        text = (ROOT / item / "PROVENANCE.md").read_text(encoding="utf-8")
        if "not stated" not in text:
            raise ValueError(f"{item}: PROVENANCE.md now states an origin; revise the exclusion")
    return data


def record_count(path: Path) -> int | None:
    """Count data records; None where the file is not a row table here."""
    if path.suffix == ".csv":
        with path.open(encoding="utf-8", newline="") as handle:
            return max(0, sum(1 for _ in csv.reader(handle)) - 1)
    if path.suffix == ".json":
        return len(json.loads(path.read_text(encoding="utf-8"))["records"])
    return None


def population(count: int | None) -> str:
    """Describe population from a computed count; zero is never populated."""
    if count is None:
        return "not counted (non-tabular file)"
    return "empty (schema and citation contract only)" if count == 0 else "populated"


def _links(items: list[str]) -> str:
    return "<br>".join(f"`{item}`" for item in items) if items else "none"


def render(data: dict) -> str:
    """Return the Markdown page for the validated inventory."""
    lines = [
        "# Riser capability inventory",
        "",
        "Generated by `scripts/riser_capability/build_riser_inventory.py` from",
        "`data/riser_capability/riser_types.yml`. Edit the data file, not this page.",
        "",
        "## Summary",
        "",
    ]
    for status in STATUSES:
        names = "; ".join(e["name"] for e in data["riser_types"] if e["status"] == status) or "none"
        lines.append(f"- {STATUS_TEXT[status].capitalize()}: {names}.")
    worked = [e["name"] for e in data["riser_types"] if e["worked_configurations"]]
    lines.append(f"- Committed worked configurations: {'; '.join(worked) if worked else 'none at this revision'}.")
    lines += ["", "## Riser types", "",
              "| Riser type | Status | Open-source calculation | Worked configurations | Open issues |",
              "| --- | --- | --- | --- | --- |"]
    for e in data["riser_types"]:
        issues = ", ".join(f"#{n}" for n in e["open_issues"]) or "none"
        solver = " ".join(e["open_source_solver"].split())
        lines.append(f"| {e['name']} | {STATUS_TEXT[e['status']]} | {solver} | "
                     f"{_links(e['worked_configurations'])} | {issues} |")
    lines += ["", "Table 1. Capability status by riser type.", ""]
    for e in data["riser_types"]:
        lines += [f"### {e['name']}", "",
                  f"- Modules: {_links(e['modules'])}",
                  f"- Tests: {_links(e['tests'])}",
                  f"- Example inputs: {_links(e['example_inputs'])}",
                  f"- Public solver examples: {_links(e['public_solver_examples'])}",
                  f"- Input databases: {', '.join(e['databases']) or 'none'}",
                  f"- Not established: {' '.join(e['not_established'].split())}", ""]
    lines += ["## Input databases", "",
              "| Category | Path | Records | Population | Provenance mechanism |",
              "| --- | --- | --- | --- | --- |"]
    for row in data["databases"]:
        count = record_count(ROOT / row["path"])
        shown = "-" if count is None else str(count)
        lines.append(f"| {row['category']} | `{row['path']}` | {shown} | {population(count)} | {row['provenance']} |")
    for row in data["absent_database_categories"]:
        issue = f"issue #{row['issue']}" if row["issue"] else "no issue yet"
        lines.append(f"| {row['category']} | none | - | absent ({issue}) | none |")
    lines += ["", "Table 2. Riser input databases; record counts are computed at generation.", "",
              "## Excluded model folders", "",
              " ".join(data["excluded_model_folders"]["reason"].split()), ""]
    lines += [f"- `{item}`" for item in data["excluded_model_folders"]["paths"]]
    lines += ["", "## Reproduce", "", "```bash",
              "PYTHONPATH=src uv run python scripts/riser_capability/build_riser_inventory.py --check",
              "PYTHONPATH=src uv run python -m pytest tests/riser_capability/test_riser_inventory.py -q",
              "```", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render(load_inventory())
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.stderr.write("riser-capability-inventory.md is out of date\n")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
