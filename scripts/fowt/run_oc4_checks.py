"""Run the licence-free checks for the NREL 5 MW / OC4-DeepCwind fowt model.

    python scripts/fowt/run_oc4_checks.py

Writes ``docs/domains/orcaflex/examples/fowt/oc4-deepcwind/spec.yml`` and
``results.json``. No licensed solver is used.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import yaml

from digitalmodel.floating_wind.fowt_static_checks import (
    equilibrium,
    model_from_spec,
    natural_periods,
)
from digitalmodel.floating_wind.oc4_orcaflex_spec import build_oc4_spec, load_sources

ROOT = Path(__file__).resolve().parents[2]
FOLDER = ROOT / "docs" / "domains" / "orcaflex" / "examples" / "fowt" / "oc4-deepcwind"
REPORT = "Robertson et al. (2014), NREL/TP-5000-60601"
LIN = "OpenFAST linearisation in OpenFAST/r-test (basis.yml comparators)"
PHASE2 = "Robertson et al. (2014), NREL/CP-5000-61154, text values"


def compare(quantity, unit, computed, comparator, source, tolerance):
    computed, comparator = float(computed), float(comparator)
    deviation = (computed - comparator) / comparator
    return {"quantity": quantity, "unit": unit, "computed": computed, "comparator": comparator,
            "comparator_source": source, "tolerance": tolerance, "deviation": deviation,
            "within_tolerance": bool(abs(deviation) <= tolerance)}


def main() -> int:
    basis, data = load_sources()
    spec = build_oc4_spec(basis, data)
    FOLDER.mkdir(parents=True, exist_ok=True)
    (FOLDER / "spec.yml").write_text(
        "# NREL 5 MW on the OC4-DeepCwind semi-submersible; generated by\n"
        "# scripts/fowt/run_oc4_checks.py. LC0 static equilibrium. Units: te, kN, m, s.\n"
        + yaml.safe_dump(spec, sort_keys=False, width=100), encoding="utf-8", newline="\n")
    model = model_from_spec(spec)
    still = equilibrium(model)
    q0 = still["position"]
    freq = natural_periods(model, data, q0)
    inf = natural_periods(model, data, q0, infinite_frequency_added_mass=True)
    k = freq["mooring_stiffness"]
    published = basis["published"]
    lin = basis["comparators"]["openfast_linearisation_periods"]["value"]
    text = published["natural_frequencies_text"]["value"]
    hydro = spec["fowt"]["hull"]["hydrostatic_stiffness_excluding_gravity"]
    p5 = f"{REPORT}, Eq. (5-14) and (5-15), printed page 27"
    comparisons = [
        compare("Displaced volume", "m3", spec["fowt"]["hull"]["displaced_volume"],
                published["displacement"]["value"], f"{REPORT}, Table 4-6", 0.01),
        compare("Buoyancy force", "N", model.rho * model.g * model.volume,
                published["buoyancy_force"]["value"], f"{REPORT}, Table 4-6", 0.01),
        compare("Heave hydrostatic stiffness", "N/m", hydro[0][0] * 1000,
                published["hydrostatic_stiffness"]["value"][2], f"{REPORT}, Table 4-6", 0.02),
        compare("Pitch hydrostatic stiffness, weight term excluded", "N m/rad", hydro[2][2] * 1000,
                published["hydrostatic_stiffness"]["value"][4], f"{REPORT}, Table 4-6", 0.03),
        compare("Mooring vertical load at the undisplaced position", "N",
                still["mooring_load"][2], -1.839e6, p5, 0.03),
        compare("Mooring stiffness, surge", "N/m", k[0, 0], 7.08e4, p5, 0.03),
        compare("Mooring stiffness, heave", "N/m", k[2, 2], 1.91e4, p5, 0.03),
        compare("Mooring stiffness, pitch", "N m/rad", k[4, 4], 8.73e7, p5, 0.03),
        compare("Mooring stiffness, yaw", "N m/rad", k[5, 5], 1.17e8, p5, 0.03),
        compare("Mooring stiffness, surge-pitch", "N/rad", k[0, 4], -1.08e5, p5, 0.05),
    ]
    tol = {"surge": 0.10, "heave": 0.05, "pitch": 0.05, "yaw": 0.10}
    for mode in ("surge", "heave", "pitch", "yaw"):
        comparisons.append(compare(f"Natural period, {mode}", "s", freq["periods"][mode],
                                   lin[mode], LIN, tol[mode]))
    bands = {"surge": (0.005, 0.015), "heave": (0.0575, 0.0585), "pitch": (0.035, 0.045)}
    text_checks = {
        mode: {"computed_frequency": 1.0 / freq["periods"][mode], "quoted": text[mode],
               "rounding_band": bands[mode],
               "inside_band": bool(bands[mode][0] <= 1.0 / freq["periods"][mode] <= bands[mode][1])}
        for mode in bands}
    result = {
        "description": "Licence-free checks of the generated NREL 5 MW / OC4-DeepCwind fowt "
                       "model (rigid representation). SI units.",
        "system_mass": model.mass,
        "system_centre_of_gravity": model.cog.tolist(),
        "still_water": {"surge": q0[0], "heave": q0[2], "pitch_deg": math.degrees(q0[4]),
                        "lines": still["lines"]},
        "natural_periods": freq["periods"],
        "natural_periods_infinite_frequency_added_mass": inf["periods"],
        "openfast_linearisation_periods": lin,
        "mooring_stiffness": np.asarray(k).tolist(),
        "comparisons": comparisons,
        "phase_ii_text_frequencies": text_checks,
    }
    (FOLDER / "results.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8",
                                         newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
