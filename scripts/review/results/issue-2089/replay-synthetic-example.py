"""Replay a SYNTHETIC integration example; never run or parse native GHS."""
import hashlib
import json
import tempfile
from html import escape
from pathlib import Path

from digitalmodel.solvers.ghs.contracts import prepare_canary, preview_approval, preview_runfile
from digitalmodel.solvers.ghs.comparison import compare_normalized
from digitalmodel.solvers.ghs.runner import run_synthetic_capture

ROOT = Path(__file__).resolve().parents[4]
OUTPUT = Path(__file__).resolve().parent
GEOMETRY = b"SYNTHETIC placeholder: not a GHS geometry definition.\n"
FIELDS = ('volume_m3','mass_t','waterplane_m2','lcb_m','lcf_m','tcb_m','tcf_m','kb_m','bmt_m','bml_m')
# Independent declared values, not generated by the implementation's oracle.
VALUES = [
 ('1', ['200','200','200','10','10','0','0','0.5','8.333333333333','33.333333333333']),
 ('2', ['400','400','200','10','10','0','0','1','4.166666666667','16.666666666667']),
 ('3', ['600','600','200','10','10','0','0','1.5','2.777777777778','11.111111111111']),
]


def encoded(value):
    return json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False,allow_nan=False).encode()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def inputs():
    frame={'length':'m','mass':'tonne','volume':'m3','area':'m2','x':'forward_from_aft',
           'y':'port_from_centreplane','z':'up_from_baseline','depth':'origin_depth_m'}
    request={'case_id':'synthetic-box-example','geometry_sha256':sha(GEOMETRY),
        'depths_m':['1','2','3'],'density_kg_m3':'1000','units_frame':frame,
        'tolerance_profile':{'relative':'0.001','coordinate_m':'0.005','waterplane_m2':'0.01',
                             'mass_t':'0.1','volume_m3':'0.1'},
        'resource_limits':{'wall_timeout_seconds':120,'max_instances':1,
                          'max_artifact_bytes':8388608,'max_total_bytes':33554432}}
    runtime={'schema_version':1,'profile_id':'synthetic-runtime','platform':'windows',
        'executable':'C:/Synthetic/GHS.EXE','executable_sha256':'0'*64,'version':'synthetic',
        'work_dir':'C:/Synthetic Work','temp_dir':'C:/Synthetic Temp',
        'command_profile':'provisional_not_runnable','containment_profile':'unqualified'}
    policy={'schema_version':1,'report_name':'canary.pf','diagnostic_profile':'unqualified',
            'max_artifact_bytes':8388608,'max_total_bytes':33554432}
    return request,runtime,policy


def normalized_rows(report_sha):
    return [{'depth_m':depth,'values':dict(zip(FIELDS,values)),
        'references':{key:{'artifact_sha256':report_sha,'line':number+2,'resolution':'0.000000000001',
                           'transformation_reference':'declared-synthetic-normalized-values'} for key in FIELDS}}
        for number,(depth,values) in enumerate(VALUES)]


def report_html(comparison):
    rows=''.join('<tr>'+''.join('<td>'+escape(str(row[k]))+'</td>' for k in
        ('depth_m','quantity','actual','expected_rational','tolerance_rational','passed'))+'</tr>'
        for row in comparison['comparisons'])
    return ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        '<title>Synthetic GHS integration rehearsal</title><style>'
        'body{font:16px/1.5 system-ui;max-width:1100px;margin:auto;padding:24px}'
        'td,th{padding:8px;border:1px solid #bcc}table{border-collapse:collapse}'
        '.table{overflow-x:auto}</style></head><body><h1>Synthetic integration rehearsal</h1>'
        '<p>Software verification only. No native GHS geometry, execution or report parsing occurred. '
        'The input is a placeholder and all numerical rows are independent synthetic assertions.</p>'
        '<p>'+escape(comparison['conclusion'])+'</p><p>Licensed execution verified: false. '
        'Engineering review remains pending; no project-vessel conclusion is supported.</p>'
        '<p><a href="../../../scripts/review/results/issue-2089/synthetic-example-result.json">Evidence</a></p>'
        '<div class="table"><table><tr><th>Depth m</th><th>Quantity</th><th>Actual assertion</th>'
        '<th>Expected exact</th><th>Tolerance exact</th><th>Within tolerance</th></tr>'+rows+
        '</table></div></body></html>')


def main():
    request,runtime,policy=inputs()
    packet=prepare_canary(request,runtime,policy,GEOMETRY)
    receipt={'schema_version':1,'packet_sha256':packet['packet_sha256'],
        'runtime_profile_sha256':packet['runtime_profile_sha256'],'approval_reference':'synthetic-preview-only',
        'expires_at':'2026-09-12T00:00:00Z','nonce':'synthetic-preview-nonce'}
    preview=preview_approval(receipt,packet,approved_digest=packet['packet_sha256'],
        now='2026-09-11T00:00:00Z',consumed_nonces=[])
    assert preview['launch_allowed'] is False
    report=(','.join(('depth_m',*FIELDS))+'\n'+''.join(','.join((depth,*values))+'\n'
        for depth,values in VALUES)).encode()
    def backend(**kwargs):
        assert kwargs['argv'][1]=='/R:canary.rf'
        yield {'kind':'stdout','data':b'SYNTHETIC process double; no executable launched\n'}
        yield {'kind':'report','data':report}
        yield {'kind':'exit','returncode':0}
    with tempfile.TemporaryDirectory(prefix='ghs2089-example-') as folder:
        capture=run_synthetic_capture(packet,request,runtime,policy,GEOMETRY,Path(folder)/'stage',backend)
    assert capture['state']=='capture_unqualified'
    assert capture['artifact_hashes']['report']==sha(report)
    evidence={'schema_version':1,'evidence_kind':'synthetic_normalized','units_frame':request['units_frame'],
        'execution_receipt':{'reference':'synthetic-example-result.json#capture','sha256':sha(encoded(capture))},
        'qualification_profile':{'reference':'synthetic-example-input.json#policy','sha256':sha(encoded(policy))},
        'artifacts':[{'sha256':sha(report),'byte_count':len(report)}]}
    comparison=compare_normalized(packet,normalized_rows(sha(report)),evidence)
    assert comparison['state']=='comparison_passed_unreviewed' and len(comparison['comparisons'])==30
    assert comparison['licensed_execution_verified'] is False
    result={'scope':'synthetic only; no native geometry/format/execution qualification',
        'packet':packet,'approval_preview':preview,'capture':capture,'comparison':comparison,
        'implementation_hashes':{p.name:sha(p.read_bytes()) for p in sorted((ROOT/'src/digitalmodel/solvers/ghs').glob('*.py'))}}
    (OUTPUT/'synthetic-example-input.json').write_bytes(encoded({'request':request,'runtime':runtime,'policy':policy})+b'\n')
    (OUTPUT/'synthetic-example-result.json').write_bytes(encoded(result)+b'\n')
    (OUTPUT/'synthetic-normalized.csv').write_bytes(report)
    (OUTPUT/'synthetic-geometry-placeholder.txt').write_bytes(GEOMETRY)
    (OUTPUT/'runfile-preview.txt').write_bytes(preview_runfile())
    dest=ROOT/'docs/domains/ghs/2026-09-11-m1-synthetic.html';dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(report_html(comparison),encoding='utf-8')
    print(json.dumps({'comparisons':30,'state':comparison['state'],'native_execution':False,
                      'packet_sha256':packet['packet_sha256']}))


if __name__=='__main__':
    main()
