"""Build the MYSTRAN decks for NAFEMS LE1 and a constant-stress patch test (standard library only).

Card formats reproduce the module repository's MYSTRAN writer
src/digitalmodel/solvers/mystran/bdf_writer.py at commit f9c058d6ef4e69d01630d90ea90033b47ce9d30f
(executive and case control lines 197-211; GRID 218-219; CQUAD4 via _split_card 328-343; PSHELL 139-141;
MAT1 75; SPC1 346-352 and SPC 254; FORCE 258-262; ENDDATA 269; number format _f 317-325). That writer
imports numpy, which this workstation's Python lacks, so the formats are reproduced here.

LE1 (units N, mm, MPa): quarter elliptic membrane between the inner ellipse (2000, 1000) and the outer
ellipse (3250, 2750); thickness 100 mm; E = 210000 MPa, nu = 0.3; outward normal pressure 10 MPa on the
outer edge; symmetry: u_x = 0 on x = 0, u_y = 0 on y = 0. Source of the definition: repository
axia-fem, solver/scripts/gen_nafems.py, commit 884ec6fe7b74f0a1a9b9ae55e57ccfba625a93c1, lines 44-106
(MIT licence), with the same geometry, material and load in repository featool-multiphysics,
examples/ex_planestress5.m, commit 8207417131bc90534931a694a5d8d28ec17ca9fa, lines 26-27 and 39-90.
Mesh: the same mapping as gen_nafems.py lines 21-24 (x = a(s) cos t, y = b(s) sin t, a and b linear in s),
CQUAD4 elements, nr radial by nt hoop. The edge pressure is applied as consistent nodal forces: each
straight outer edge segment carries p t (dy, -dx), half to each end node.
Out-of-plane and drilling freedoms (3456) are constrained at every grid (in-plane problem).

Patch test: a 2 x 1 mm patch of five irregular CQUAD4 elements (four interior nodes chosen here), all
boundary nodes displaced as u = 1e-3 x + 0.5e-3 y, v = 0.5e-3 x + 1e-3 y; the exact stress is uniform.

Usage: python -I build_decks.py <package dir>
"""
import math
import sys
from pathlib import Path

E, NU, T, P = 210000.0, 0.3, 100.0, 10.0
AI, BI, AO, BO = 2000.0, 1000.0, 3250.0, 2750.0
MESHES = [(8, 24), (16, 48), (32, 96)]


def f(x: float) -> str:                                # _f, lines 317-325
    """Format a free-field real using the supplied writer's convention."""
    x = float(x)
    if x == 0.0:
        return "0.0"
    s = f"{x:.8G}"
    if "." not in s and "E" not in s:
        s += ".0"
    return s


def spc1(dofs: str, gids: list[int]) -> list[str]:       # lines 346-352
    """Split fixed-component constraints into six-grid cards."""
    return ["SPC1,1,%s,%s" % (dofs, ",".join(str(g) for g in gids[i:i + 6])) for i in range(0, len(gids), 6)]


def header(stem: str, title: str, spc: bool, load: bool) -> list[str]:
    """Create executive and case control for the supplied static problem."""
    L = ["ID %s,DIGITALMODEL" % stem.upper()[:8], "SOL 101", "CEND", "TITLE = %s" % title,
         "SUBTITLE = generated by digitalmodel.solvers.mystran"]
    if spc:
        L.append("SPC = 1")
    if load:
        L.append("LOAD = 1")
    L += ["DISP = ALL", "STRESS = ALL", "SPCFORCE = ALL", "BEGIN BULK"]
    return L


def le1(nr: int, nt: int) -> tuple[str, list[str], int]:
    """Build the mapped quarter-membrane mesh and consistent edge loads."""
    gid, xy = {}, []
    for i in range(nr + 1):
        for j in range(nt + 1):
            s, th = i / nr, (j / nt) * math.pi / 2
            a, b = AI + s * (AO - AI), BI + s * (BO - BI)
            x, y = a * math.cos(th), b * math.sin(th)
            if j == nt:
                x = 0.0
            if j == 0:
                y = 0.0
            xy.append((x, y))
            gid[(i, j)] = len(xy)
    stem = "le1_%dx%d" % (nr, nt)
    L = header(stem, "NAFEMS LE1 elliptic membrane, CQUAD4 %d radial x %d hoop" % (nr, nt), True, True)
    L.append("$ --- grids ---")
    for k, (x, y) in enumerate(xy, start=1):
        L.append("GRID,%d,,%s,%s,%s" % (k, f(x), f(y), f(0.0)))
    L.append("$ --- elements ---")
    eid = 0
    for i in range(nr):
        for j in range(nt):
            eid += 1
            # counter-clockwise in the xy plane (normal +z): (i,j) -> (i+1,j) -> (i+1,j+1) -> (i,j+1)
            L.append("CQUAD4,%d,1,%d,%d,%d,%d" % (eid, gid[(i, j)], gid[(i + 1, j)], gid[(i + 1, j + 1)], gid[(i, j + 1)]))
    L += ["$ --- properties and materials ---", "PSHELL,1,1,%s,1,,1" % f(T), "MAT1,1,%s,,%s,%s" % (f(E), f(NU), f(0.0))]
    L.append("$ --- single-point constraints ---")
    L += spc1("3456", list(range(1, len(xy) + 1)))
    L += spc1("2", [gid[(i, 0)] for i in range(nr + 1)])
    L += spc1("1", [gid[(i, nt)] for i in range(nr + 1)])
    L.append("$ --- loads ---")
    fx: dict[int, list[float]] = {}
    for j in range(nt):
        p0, p1 = xy[gid[(nr, j)] - 1], xy[gid[(nr, j + 1)] - 1]
        dx, dy = p1[0] - p0[0], p1[1] - p0[1]
        for g in (gid[(nr, j)], gid[(nr, j + 1)]):
            fx.setdefault(g, [0.0, 0.0])
            fx[g][0] += 0.5 * P * T * dy
            fx[g][1] += 0.5 * P * T * (-dx)
    for g in sorted(fx):
        m = math.hypot(*fx[g])
        L.append("FORCE,1,%d,,%s,%s,%s,%s" % (g, f(m), f(fx[g][0] / m), f(fx[g][1] / m), f(0.0)))
    L.append("ENDDATA")
    return stem, L, gid[(0, 0)]


def patch() -> tuple[str, list[str]]:
    """Build the five-element patch with prescribed linear displacements."""
    # outer rectangle corners and four interior nodes (irregular), 5 quadrilaterals
    pts = [(0.0, 0.0), (2.0, 0.0), (2.0, 1.0), (0.0, 1.0), (0.4, 0.2), (1.4, 0.3), (1.6, 0.7), (0.3, 0.8)]
    quads = [(1, 2, 6, 5), (2, 3, 7, 6), (3, 4, 8, 7), (4, 1, 5, 8), (5, 6, 7, 8)]
    L = header("patch", "Constant-stress patch test, five irregular CQUAD4", True, False)
    L.append("$ --- grids ---")
    for k, (x, y) in enumerate(pts, start=1):
        L.append("GRID,%d,,%s,%s,%s" % (k, f(x), f(y), f(0.0)))
    L.append("$ --- elements ---")
    for e, q in enumerate(quads, start=1):
        L.append("CQUAD4,%d,1,%d,%d,%d,%d" % ((e,) + q))
    L += ["$ --- properties and materials ---", "PSHELL,1,1,%s,1,,1" % f(T), "MAT1,1,%s,,%s,%s" % (f(E), f(NU), f(0.0))]
    L.append("$ --- single-point constraints ---")
    L += spc1("3456", list(range(1, 9)))
    for k in range(1, 5):
        x, y = pts[k - 1]
        u, v = 1e-3 * x + 0.5e-3 * y, 0.5e-3 * x + 1e-3 * y
        for dof, val in (("1", u), ("2", v)):
            if val == 0.0:
                L += spc1(dof, [k])
            else:
                L.append("SPC,1,%d,%s,%s" % (k, dof, f(val)))  # line 254
    L.append("ENDDATA")
    return "patch", L


def main() -> None:
    """Write the four deterministic input decks to the requested package."""
    pkg = Path(sys.argv[1])
    (pkg / "inputs").mkdir(exist_ok=True)
    for nr, nt in MESHES:
        stem, L, d = le1(nr, nt)
        (pkg / "inputs" / (stem + ".bdf")).write_text("\n".join(L) + "\n", encoding="ascii", newline="\n")
        print("wrote inputs/%s.bdf: %d grids, %d CQUAD4, point D = grid %d" % (stem, (nr + 1) * (nt + 1), nr * nt, d))
    stem, L = patch()
    (pkg / "inputs" / "patch.bdf").write_text("\n".join(L) + "\n", encoding="ascii", newline="\n")
    print("wrote inputs/patch.bdf: 8 grids, 5 CQUAD4")


if __name__ == "__main__":
    main()
