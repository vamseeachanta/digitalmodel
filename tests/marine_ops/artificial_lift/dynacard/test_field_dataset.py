def test_scoring_counts_correct_over_total_and_thin_classes(
    tmp_path, permission, provenance
):
    """Hand tally: two normal cards, one correct; one gas card, one correct.

    At the explicitly chosen fixture reporting count of two, normal recall is
    1/2; gas is too thin. The heuristic always predicts normal: 2/2 normal.
    These are adapter checks, never field accuracy. Formula: 2025 thesis,
    equations (2.6), (2.8). Interval implementation has its own hand tests.
    """
    rows = [("[0,0,1,1]", "[0,1,1,0]", code) for code in ("healthy", "healthy", "gas")]
    dataset = load(
        tmp_path,
        permission,
        provenance,
        rows=rows,
        label_map={"healthy": "Normal", "gas": "Gas interference"},
    )
    answers = iter(["NORMAL", "GAS_LOCK", "GAS_INTERFERENCE"])
    result = evaluate_export(
        dataset,
        minimum_count=2,
        confidence=0.95,
        ml_classifier=lambda card: next(answers),
        heuristic_classifier=lambda card: "NORMAL",
    )
    per_class = result["methods"]["ml"]["per_class"]
    assert result["count"] == 3
    assert per_class["NORMAL"]["accuracy"] == 0.5
    assert per_class["GAS_INTERFERENCE"]["status"] == "too thin to score"
    assert "accuracy" not in per_class["GAS_INTERFERENCE"]
    assert result["methods"]["heuristic"]["per_class"]["NORMAL"]["accuracy"] == 1
    assert result["published_table_total"] == 50112
    assert result["received_count"] == 3
    json.dumps(result, allow_nan=False)


