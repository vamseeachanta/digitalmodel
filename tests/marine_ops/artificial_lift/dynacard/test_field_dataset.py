def test_import_retains_permission_and_byte_identity(tmp_path, permission, provenance):
    dataset = load(tmp_path, permission, provenance)
    assert dataset.permission == permission
    assert (
        dataset.source_sha256
        == hashlib.sha256((tmp_path / "cards.csv").read_bytes()).hexdigest()
    )
    report = evaluate_export(dataset, minimum_count=2, confidence=0.95)
    assert report["permission_reference"] == "fixture-terms"
    assert report["source_sha256"] == dataset.source_sha256
    assert report["attribution"] == permission.attribution
    assert report["codebook_reference"] == "fixture dictionary"


