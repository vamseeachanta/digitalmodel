@pytest.mark.parametrize(
    "field,value",
    [
        ("written_agreement", False),
        ("benchmark_allowed", False),
        ("written_agreement", "yes"),
        ("benchmark_allowed", 1),
        ("evidence_reference", " "),
        ("licence", ""),
        ("attribution", ""),
    ],
)
def test_permission_fails_before_opening_input(
    tmp_path, permission, provenance, field, value
):
    with pytest.raises(ValueError, match="permission|Permission"):
        load_three_column_export(
            tmp_path / "absent.csv",
            expected_sha256="0" * 64,
            permission=replace(permission, **{field: value}),
            provenance=provenance,
            label_map={},
            codebook_reference="fixture",
            card_space="pump",
            units={"position": "in", "load": "lbf"},
        )


