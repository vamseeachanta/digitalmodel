def csv_export(tmp_path, rows, header=("loads", "positions", "type")):
    text = io.StringIO(newline="")
    writer = csv.writer(text)
    writer.writerow(header)
    writer.writerows(rows)
    path = tmp_path / "cards.csv"
    path.write_text(text.getvalue(), encoding="utf-8")
    return path, hashlib.sha256(path.read_bytes()).hexdigest()


def load(tmp_path, permission, provenance, rows=None, **kwargs):
    if rows is None:
        rows = [("[0, 0, 1, 1]", "[0, 1, 1, 0]", "healthy")]
    path, digest = csv_export(tmp_path, rows)
    options = dict(
        expected_sha256=digest,
        permission=permission,
        provenance=provenance,
        label_map={"healthy": "Normal"},
        codebook_reference="fixture dictionary",
        card_space="pump",
        units={"position": "in", "load": "lbf"},
    )
    options.update(kwargs)
    return load_three_column_export(path, **options)


def test_publication_inventory_is_not_received_data():
    """Sensors (2021), Table 1: hand sum of its ten printed counts = 50,112.

    10,282+260+38,298+67+172+29+6+30+895+73 = 50,112.
    This is a table total, not a statement that a file has been received.
    """
    report = acquisition_status()
    assert report["published_table_total"] == 50112
    assert report["received_count"] == 0
    assert report["status"] == "NOT_EVALUATED"
    assert len(report["crosswalk"]) == 10
    assert report["published_well_count"] == 38  # Sensors (2021), section 1.
    unmapped = {r["external_label"] for r in report["crosswalk"] if r["mode"] is None}
    assert unmapped == {
        "Tubing anchor malfunction",
        "Sensor fault - rotated card",
        "Sensor fault - line card",
    }
    assert "STUCK_PUMP" in report["unmapped_modes"]
    assert "NORMAL" not in report["unmapped_modes"]


