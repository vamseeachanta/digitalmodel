def test_page_is_offline_and_untracked(page):
    assert re.search(r"<script[^>]+src=", page) is None
    assert re.search(r"<link[^>]+stylesheet", page) is None
    assert re.search(r"<img[^>]+src=\"https?:", page) is None
    for call in ("fetch(", "XMLHttpRequest", "WebSocket", "sendBeacon", "localStorage"):
        assert call not in page
    assert "Content-Security-Policy" in page and "connect-src 'none'" in page


def test_no_internal_words_or_local_paths(page):
    text = _visible(page) + " " + " ".join(re.findall(r'href="([^"]+)"', page))
    banned = [r"(?<![A-Za-z])[A-Z]:[\\/]",r"/mnt/", r"\brds02\b", r"ace-linux", r"\bws014\b", r"vamseea\b",
              r"\bdesk\b", r"\blane\b", r"\bseat\b", r"\bCodex\b", r"\bClaude\b", r"\bPR\b",
              r"pull request", r"\breviewer", r"\bmentor"]
    for pattern in banned:
        assert re.search(pattern, text, flags=re.I) is None, pattern


