"""Dynacard article r3: built from the saved results, short body, offline charts.

The article is generated by examples/domains/artificial_lift/build_dynacard_article.py
from three saved records: the pump-card report results, the ten worked examples and
the browser application's reproduction table. These tests fix the reader-facing
contract set by the owner's review of revision 2 (13 Nov 2026).
"""
