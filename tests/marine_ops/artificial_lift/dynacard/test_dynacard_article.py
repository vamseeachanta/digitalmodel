def test_two_methods_short_in_body_compared_in_appendix(page):
    report = {r["id"]: r["value"] for r in _results(REPORT)["results"]}
    body = _visible(_body(page))
    para = re.search(r"Two numerical methods are available[^.]*\.[^.]*\.[^.]*\.", body)
    assert para is not None
    assert len(para.group(0).split()) <= 70
    appendix = _visible(page[page.index('id="appendix-b"'):])
    for key in ("gibbs_default_load_nrmse_pct", "default_reference_load_nrmse_pct",
                "gibbs_reference_load_nrmse_pct"):
        assert f"{report[key]:.2f}" in appendix


def test_examples_section_title_and_joined_view(page):
    body = _body(page)
    headings = [_visible(h) for h in re.findall(r"<h2[^>]*>(.*?)</h2>", body, flags=re.S)]
    assert "Ten worked examples" not in headings
    assert any(h.startswith("Ten pump conditions") for h in headings)
    rows = re.findall(r'<tr[^>]+data-example="(\d+)"', body)
    assert rows == [str(i) for i in range(1, 11)]
    panels = re.findall(r'<section class="example-panel"[^>]+id="example-(\d+)"', body)
    assert panels == [str(i) for i in range(1, 11)]
    for i in range(1, 11):
        panel = re.search(rf'id="example-{i}".*?</section>', body, flags=re.S).group(0)
        assert "<svg" in panel and 'class="card-pump"' in panel and 'class="prob-bar"' in panel
        assert panel.count("<li>") >= 3


def test_examples_view_agrees_with_saved_results(page):
    records = _results(EXAMPLES)["examples"]
    body = _body(page)
    matches = 0
    for record in records:
        row = re.search(rf'<tr[^>]+data-example="{record["index"]}".*?</tr>', body, flags=re.S)
        text = _visible(row.group(0))
        assert f"{record['analysis']['fillage_pct']:.0f}" in text
        assert f"{record['analysis']['fluid_load_lbf']:,.0f}" in text
        shape = record["diagnosis"]["shape_only"]
        matches += shape["classification"] == record["crosswalk_mode"]
    assert f"{matches} of the 10" in _visible(body)


