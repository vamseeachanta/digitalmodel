def test_opening_is_free_of_data_details(page):
    body = _body(page)
    first = re.search(r'<div class="opening">(.*?)</div>', body, flags=re.S).group(1)
    paragraphs = re.findall(r"<p>(.*?)</p>", first, flags=re.S)
    assert 1 <= len(paragraphs) <= 2
    assert not re.search(r"\d", _visible(first)), "no numbers in the opening paragraphs"


def test_figure_one_house_style_and_two_cards_only(page):
    body = _body(page)
    assert "Based on public data, two of the cards are shown in Figure 1." in body
    lead = body.index("Based on public data, two of the cards")
    bullets = body[lead:body.index('<figure', lead)]
    assert bullets.count("<li>") >= 3
    figure = re.search(r'<figure id="figure-1".*?</figure>', body, flags=re.S).group(0)
    assert figure.count('class="card-surface"') == 1 and figure.count('class="card-pump"') == 1
    assert "plate" not in figure.lower(), "the ten-shape panel is not in Figure 1"


