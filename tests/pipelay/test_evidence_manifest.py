@pytest.mark.parametrize("revision", ["synthetic-test-version", None])
def test_revision_comes_from_distribution_metadata(tmp_path, monkeypatch, revision):
    def version(name):
        assert name == "digitalmodel"
        if revision is None:
            raise evidence.metadata.PackageNotFoundError(name)
        return revision

    monkeypatch.setattr(evidence.metadata, "version", version)
    _, _, path = issue(tmp_path)
    assert json.loads(path.read_bytes())["tool_revision"] == (revision or "NOT_EVALUATED")


def test_writer_hashes_written_input_readback(tmp_path, monkeypatch):
    summary = tmp_path / "screening.json"
    summary.write_bytes(b'{"synthetic": true}')
    original_write = Path.write_bytes

    def write_with_newline(path, data):
        # Simulate a storage layer adding JSON whitespace after write. The
        # manifest must describe bytes on disk, never the in-memory input.
        if path.name.endswith(".input.json"):
            data += b"\n"
        return original_write(path, data)

    monkeypatch.setattr(Path, "write_bytes", write_with_newline)
    received = b'{"synthetic_input": true}'
    manifest_path = evidence.write_evidence_manifest(summary, received)
    manifest = json.loads(manifest_path.read_bytes())
    saved = (tmp_path / manifest["input"]["file"]).read_bytes()
    assert saved != received
    assert manifest["input"]["sha256"] == hashlib.sha256(saved).hexdigest()
    assert manifest["input"]["sha256"] != hashlib.sha256(received).hexdigest()


def test_all_changed_artefacts_are_reported(tmp_path):
    _, _, path = issue(tmp_path)
    manifest = json.loads(path.read_bytes())
    for name in ("input", "output"):
        artefact = path.parent / manifest[name]["file"]
        artefact.write_bytes(artefact.read_bytes() + b" ")
    assert evidence.verify_evidence_manifest(path) == {
        "ok": False, "failures": [
            {"artefact": "input", "reason": "digest_mismatch"},
            {"artefact": "output", "reason": "digest_mismatch"},
        ],
    }


@pytest.mark.parametrize("artefact", ["input", "output", "manifest"])
def test_unreadable_file_is_refused(tmp_path, monkeypatch, artefact):
    _, summary, path = issue(tmp_path)
    target = {"input": summary.with_name(summary.name + ".input.json"),
              "output": summary, "manifest": path}[artefact]
    read_bytes = Path.read_bytes

    def refuse(target_path):
        if target_path == target:
            raise PermissionError("Synthetic unreadable artefact")
        return read_bytes(target_path)

    monkeypatch.setattr(Path, "read_bytes", refuse)
    assert evidence.verify_evidence_manifest(path) == {
        "ok": False, "failures": [{"artefact": artefact, "reason": "unreadable_file"}],
    }
