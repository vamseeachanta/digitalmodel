@pytest.mark.parametrize("fault", [
    "missing", "unowned", "drifted", "manifest_unowned", "manifest_drifted",
])
def test_publication_negative_control(tmp_path, monkeypatch, fault):
    fresh = builder.build(ROOT, tmp_path / "fresh")
    shadow = tmp_path / "shadow"
    report = shadow / PUBLISHED_REPORT
    report.parent.mkdir(parents=True)
    report.write_bytes(fresh[0].read_bytes())
    manifest = report.with_suffix(".manifest.json")
    manifest.write_bytes(fresh[1].read_bytes())
    assert_published_report(shadow, fresh)
    before = hashlib.sha256(report.read_bytes()).hexdigest()
    if fault == "missing":
        report.unlink()
        message = "Published report is missing"
    elif fault in ("unowned", "manifest_unowned"):
        unowned = PUBLISHED_REPORT if fault == "unowned" else PUBLISHED_REPORT.with_suffix(".manifest.json")
        monkeypatch.setattr(html_checker, "GENERATORS", tuple(
            replace(entry, outputs=tuple(path for path in entry.outputs
                                        if path != unowned.as_posix()))
            for entry in html_checker.GENERATORS
        ))
        if fault == "unowned":
            assert any(PUBLISHED_REPORT.as_posix() in error
                       for error in html_checker.validate_page_census(shadow))
        message = f"Published {'report' if fault == 'unowned' else 'manifest'} has no generator ownership"
    elif fault == "drifted":
        report.write_bytes(report.read_bytes() + b"\n<!-- stale output -->\n")
        assert hashlib.sha256(report.read_bytes()).hexdigest() != before
        message = "Published report has drifted"
    else:
        manifest.write_bytes(b"{}\n")
        message = "Published manifest has drifted"
    with pytest.raises(AssertionError, match=message):
        assert_published_report(shadow, fresh)
    report.write_bytes(fresh[0].read_bytes())
    manifest.write_bytes(fresh[1].read_bytes())
    assert hashlib.sha256(report.read_bytes()).hexdigest() == before


