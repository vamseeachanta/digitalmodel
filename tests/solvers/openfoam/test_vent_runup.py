"""Independent conservation and geometry examples for the rolling vent gate.

All numbers below are synthetic test inputs, not engineering acceptance limits.
Arithmetic is written out rather than generated by the implementation.
"""

from dataclasses import replace

import pytest

from digitalmodel.solvers.openfoam.vent_runup import (
    assess_vent_hold,
    worst_fill_resonant_cases,
)
from digitalmodel.solvers.openfoam.case_coupling import synthetic_sweep_case


def assess(series=(), **changes):
    inputs = dict(
        case_id="synthetic", initial_volume_m3=100.0, tank_height_m=10.0,
        fill_fraction=0.8, roll_period_s=2.0, cycles=2,
        tolerance_pct=0.1, max_sample_gap_s=1.0,
    )
    inputs.update(changes)
    return assess_vent_hold(series, **inputs)


def evidence(**changes):
    data = dict(
        case_id="synthetic", variant="vent_top", frame="tank",
        start_time_s=0.0, end_time_s=4.0, peak_elevation_m=9.5,
        source="Synthetic hand calculation in test_vent_runup.py",
    )
    data.update(changes)
    return data


def test_headroom_and_volume_hand_calculation():
    """H=10, F=.8 => h=8, freeboard=2; zmax=9.5 => eta=1.5, gap=.5.

    Constant V=100 throughout 2 cycles * 2 s => zero volume deviation.
    """
    result = assess([(t, 100.0) for t in range(5)], runup_evidence=evidence())
    assert result["checks"] == dict(volume="PASS", coverage="PASS", headroom="PASS")
    assert result["case_status"] == "PASS"
    assert result["nominal_freeboard_m"] == pytest.approx(2.0)
    assert result["peak_runup_m"] == pytest.approx(1.5)
    assert result["remaining_headroom_m"] == pytest.approx(0.5)


def test_return_to_initial_does_not_hide_transient_loss():
    """100 -> 98 -> 100: final drift=0, maximum deviation=2/100*100=2%."""
    result = assess([(0, 100), (1, 98), (2, 100), (3, 100), (4, 100)])
    assert result["final_drift_pct"] == 0
    assert result["max_abs_deviation_pct"] == pytest.approx(2.0)
    assert result["checks"]["volume"] == "FAIL"
    assert result["case_status"] == "FAIL"


def test_first_written_sample_does_not_replace_initialized_volume():
    """First sample already lost 1/100*100=1%; later values cannot hide it."""
    result = assess([(t, 99) for t in range(1, 5)])
    assert result["max_abs_deviation_pct"] == pytest.approx(1.0)
    assert result["checks"]["volume"] == "FAIL"


@pytest.mark.parametrize("peak", [10.0, 10.5])
def test_touching_roof_requires_remedy_even_if_volume_holds(peak):
    """zmax >= H means no strictly positive clearance; no empirical limit."""
    result = assess([(t, 100) for t in range(5)],
                    runup_evidence=evidence(peak_elevation_m=peak))
    assert result["checks"]["headroom"] == "FAIL"
    assert result["remedy"] == "raise_domain_and_repeat"
    assert result["case_status"] == "FAIL"


@pytest.mark.parametrize("series", [[], [(0, 100)], [(0, 100), (4, 100)],
                                   [(t, 100) for t in range(4)]])
def test_missing_short_or_sparse_history_is_not_evaluated(series):
    result = assess(series, runup_evidence=evidence())
    assert result["checks"]["coverage"] == "NOT_EVALUATED"
    assert result["case_status"] == "NOT_EVALUATED"


def test_missing_runup_does_not_promote_volume_pass_to_clearance():
    result = assess([(t, 100) for t in range(5)])
    assert result["checks"]["volume"] == "PASS"
    assert result["checks"]["headroom"] == "NOT_EVALUATED"
    assert result["remaining_headroom_m"] is None
    assert result["case_status"] == "NOT_EVALUATED"


@pytest.mark.parametrize("changes", [
    {"case_id": "other"}, {"variant": "baseline_full_height_outlet"},
    {"frame": "global"}, {"start_time_s": 1}, {"end_time_s": 3},
    {"source": ""}, {"peak_elevation_m": float("nan")},
])
def test_inapplicable_runup_is_rejected(changes):
    with pytest.raises(ValueError):
        assess([(t, 100) for t in range(5)], runup_evidence=evidence(**changes))


@pytest.mark.parametrize("changes", [
    {"initial_volume_m3": 0}, {"tank_height_m": float("nan")},
    {"fill_fraction": 1}, {"cycles": 0}, {"roll_period_s": -1},
    {"tolerance_pct": float("inf")}, {"max_sample_gap_s": 0},
])
def test_invalid_inputs_fail_closed(changes):
    with pytest.raises(ValueError):
        assess(**changes)


@pytest.mark.parametrize("series", [
    [(1, 100), (0, 100)], [(0, 100), (0, 100)],
    [(0, 100), (1, float("nan"))], [(0, 100), (1, -1)],
])
def test_invalid_history_fails_closed(series):
    with pytest.raises(ValueError):
        assess(series)


def test_selection_keeps_all_high_fill_near_resonance_ties():
    """Hand ordering: .8 resonant rows b,c dominate .5 and nonresonant .9."""
    row = synthetic_sweep_case()
    rows = [replace(row, case_id="a", fill_fraction=.5),
            replace(row, case_id="c", fill_fraction=.8),
            replace(row, case_id="b", fill_fraction=.8),
            replace(row, case_id="d", fill_fraction=.9, near_resonance=False)]
    assert [r.case_id for r in worst_fill_resonant_cases(rows)] == ["b", "c"]
    assert worst_fill_resonant_cases([]) == ()
