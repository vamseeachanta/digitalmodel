def test_missing_constraint_or_excursion_cannot_win(atlas, responses, limits):
    b = responses["b"]
    responses["b"] = replace(
        b,
        excursions=tuple(
            replace(e, interference_clearance_m=None) for e in b.excursions
        ),
    )
    result = rank_buoyancy_candidates(atlas, responses, limits)
    assert result.candidates[0].case_id == "a"
    assert result.candidates[1].constraint_status == "NOT_EVALUATED"
    responses["b"] = replace(b, excursions=b.excursions[:2])
    missing = rank_buoyancy_candidates(atlas, responses, limits).candidates[1]
    assert missing.screen_status == "NOT_EVALUATED"
    assert missing.rank is None


