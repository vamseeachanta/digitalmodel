def test_scalar_transfer_and_spectral_hand_calculation(atlas, responses, limits):
    """Application of computers in fatigue analysis (1985), §3.3.1.

    Synthetic motion PSD [0,1,0] at f=[0,1,2] Hz integrates to variance 1.
    A stress envelope (4,2,6) over a caller's 2 m excursion gives gains
    (2,1,3) MPa/m and stress variances (4,1,9) MPa². For the TDZ,
    m2_angular=(2*pi)^2*m0, hence nu0=1 Hz. Choose invented S-N m=2,
    A=1000 and T=10 s. Rayleigh E[range²]=8*m0; D=nu0*T*8*m0/A.
    A TDZ damages=(.08,.72), B=(.02,.18); no certified damage is implied.
    """
    basis = SpectralBasis(2.0, 3.0, 10.0, "synthetic power-law S-N inputs")
    for key, response in list(responses.items()):
        spectra = stress_spectra_from_excursions(
            response,
            (0.0, 1.0, 2.0),
            (0.0, 1.0, 0.0),
            2.0,
            "synthetic scalar transfer; no dynamic validation",
        )
        responses[key] = replace(response, spectra=spectra)
    result = rank_buoyancy_candidates(atlas, responses, limits, basis)
    b, a = result.candidates
    assert a.screen_spectral_damage == pytest.approx((0.08, 0.72))
    assert b.screen_spectral_damage == pytest.approx((0.02, 0.18))
    assert a.spectral_arc_length_m == (50.0, 100.0)
    assert a.spectral_status == "EVALUATED_SCREENING"
    assert a.certify_status == b.certify_status == "NOT_EVALUATED"
    assert result.citations


def test_zero_spectrum_has_true_zero_damage(atlas, responses, limits):
    """Zero variance implies zero alternating stress, hence zero damage."""
    response = responses["b"]
    spectra = tuple(
        StressSpectrum(s, (0.0, 1.0, 2.0), (0.0, 0.0, 0.0), "zero input")
        for s in (50.0, 100.0)
    )
    responses["b"] = replace(response, spectra=spectra)
    row = rank_buoyancy_candidates(
        atlas,
        responses,
        limits,
        SpectralBasis(2.0, 3.0, 10.0, "synthetic S-N"),
    ).candidates[0]
    assert row.screen_spectral_damage == (0.0, 0.0)


