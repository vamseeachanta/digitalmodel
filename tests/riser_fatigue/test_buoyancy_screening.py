def test_worked_example_json_matches_hand_answer():
    """Read back the example: D=.08*variance gives B=.18, A=.72, C=.045."""
    import contextlib
    import io
    import json
    from pathlib import Path
    import runpy

    example = (
        Path(__file__).resolve().parents[2]
        / "examples/riser_fatigue/buoyancy_screening.py"
    )
    output = io.StringIO()
    with contextlib.redirect_stdout(output):
        runpy.run_path(str(example), run_name="__main__")
    result = json.loads(output.getvalue())
    rows = result["candidates"]
    assert [r["case_id"] for r in rows] == ["b", "a", "c"]
    assert [r["rank"] for r in rows] == [1, 2, None]
    assert [max(r["screen_spectral_damage"]) for r in rows] == pytest.approx(
        [0.18, 0.72, 0.045]
    )
    assert rows[2]["constraint_status"] == "VIOLATED"
    assert all(r["certify_status"] == "NOT_EVALUATED" for r in rows)
    assert all("SCREEN" in r["validity_boundary"] for r in rows)


def test_limit_equality_passes_and_negative_clearance_fails(atlas, responses, limits):
    """100<=100, 20>=20, 40>=40 and 3>=3; negative interference violates 3 m."""
    limits = replace(
        limits,
        max_top_tension_N=100.0,
        min_bend_radius_m=20.0,
        min_hog_clearance_m=40.0,
        min_interference_clearance_m=3.0,
    )
    assert all(
        r.constraint_status == "FEASIBLE"
        for r in rank_buoyancy_candidates(atlas, responses, limits).candidates
    )
    a = responses["a"]
    responses["a"] = replace(
        a,
        excursions=(
            replace(a.excursions[0], interference_clearance_m=-1.0),
            *a.excursions[1:],
        ),
    )
    row = next(
        r
        for r in rank_buoyancy_candidates(atlas, responses, limits).candidates
        if r.case_id == "a"
    )
    assert row.rank is None
    check = next(c for c in row.constraints if c.status == "FAIL")
    assert (check.observed, check.limit, check.comparison) == (-1.0, 3.0, ">=")


