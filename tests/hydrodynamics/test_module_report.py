ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / 'docs/reports/modules/hydrodynamics'
REBUILD = 'Rebuild with: PYTHONPATH=src uv run python docs/reports/modules/hydrodynamics/generate.py'


def load_builder():
    spec = importlib.util.spec_from_file_location('hydrodynamics_report', REPORT / 'generate.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def public_example():
    spec = importlib.util.spec_from_file_location(
        'public_seakeeping_example', ROOT / 'tests/hydrodynamics/test_seakeeping.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    example = module.TestOperabilityAnalysis()
    frequencies, rao = example.unity_raos.__wrapped__(example)
    scatter = example.scatter_diagram.__wrapped__(example)
    return frequencies, rao, scatter


def test_rebuild_and_every_worked_value(tmp_path):
    builder = load_builder()
    builder.build(tmp_path)
    for name in ('index.html', 'changes.json'):
        assert (tmp_path / name).read_bytes() == (REPORT / name).read_text(encoding='utf-8').encode('utf-8'), REBUILD
    page = (tmp_path / 'index.html').read_text(encoding='utf-8')
    payload = json.loads(re.search(
        r'<script id="example-data" type="application/json">(.*?)</script>', page, re.S)[1])
    omega, rao, scatter = public_example()
    actual = operability_analysis(omega, rao, scatter, {'heave': 2.0})
    assert payload['result'] == actual
    assert payload['inputs']['scatter'] == scatter
    assert payload['inputs']['omega'] == omega.tolist()
    assert payload['inputs']['rao'] == rao.tolist()
    assert payload['inputs']['criterion'] == 2.0
    values = builder.display_values(payload)
    rendered = re.findall(r'data-value="([^"]+)">([^<]+)</', page)
    assert set(key for key, _ in rendered) == set(values)
    for key, text in rendered:
        assert text == builder.number(values[key], key), key
    assert payload['result']['operability_pct'] == pytest.approx(90.0)
    assert [r['operable'] for r in actual['sea_state_results']] == [True, True, True, False]
    # The plotted demands and limit are the same values as the calculation.
    demands = [float(value) for value in re.findall(r'data-demand="([^"]+)"', page)]
    limits = [float(value) for value in re.findall(r'data-limit="([^"]+)"', page)]
    assert demands == pytest.approx([
        row['significant_amplitude'] for row in actual['sea_state_results']])
    assert limits == pytest.approx([payload['inputs']['criterion']] * len(demands))


@pytest.mark.parametrize('newline', [b'\r\n', b'\r'], ids=['crlf', 'cr'])
def test_rebuild_ignores_checkout_newlines(tmp_path, newline):
    """Equivalent source text must keep its hashes and generated bytes."""
    builder = load_builder()
    builder.build(tmp_path / 'lf')
    checkout = tmp_path / 'checkout'
    expected = {}
    for name in builder.SOURCES:
        content = (ROOT / name).read_text(encoding='utf-8').encode('utf-8')
        expected[name] = hashlib.sha256(content).hexdigest()
        target = checkout / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.replace(b'\n', newline))
    builder.ROOT = checkout
    builder.build(tmp_path / 'converted')
    assert builder.calculate()['source_digest_format'] == 'sha256-utf8-lf'
    assert builder.calculate()['sources'] == expected, REBUILD
    for name in ('index.html', 'changes.json'):
        assert (tmp_path / 'converted' / name).read_bytes() == (tmp_path / 'lf' / name).read_bytes(), REBUILD
    # Canonicalization must still detect substantive edits.
    target = checkout / 'docs/api/_assets/brand.css'
    target.write_bytes(target.read_bytes() + b'/* Content change. */')
    assert builder.calculate()['sources']['docs/api/_assets/brand.css'] != expected['docs/api/_assets/brand.css']


def test_build_emits_lf_with_windows_text_translation(tmp_path, monkeypatch):
    """Exercise real file writes with the Windows default newline conversion."""
    original_open = Path.open

    def windows_open(path, mode='r', buffering=-1, encoding=None, errors=None, newline=None):
        if 'w' in mode and 'b' not in mode and newline is None:
            newline = '\r\n'
        return original_open(path, mode, buffering, encoding, errors, newline)

    monkeypatch.setattr(Path, 'open', windows_open)
    load_builder().build(tmp_path)
    for name in ('index.html', 'changes.json'):
        content = (tmp_path / name).read_bytes()
        assert b'\n' in content
        assert b'\r' not in content


