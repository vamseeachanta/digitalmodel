"""Build local classic-script assets from pinned repository source data."""

import argparse
import hashlib
import json
from pathlib import Path

APP = Path(__file__).resolve().parent
ROOT = APP.parents[2]
PACKAGE = ROOT / "src/digitalmodel/marine_ops/artificial_lift/dynacard"
RESULTS = ROOT / "docs/domains/artificial_lift/dynacard-examples/results.json"


def build_examples():
    """Consume the committed results basis, surface cards and source metadata."""
    data = RESULTS.read_bytes()
    document = json.loads(data)
    keys = ("index", "slug", "english_gloss", "source_label", "crosswalk_mode",
            "crosswalk_kind", "source_doi", "dataset_url", "file_url",
            "sheet_name", "licence", "retrieval_date")
    examples = []
    for record in document["examples"]:
        example = {key: record[key] for key in keys}
        example.update(name=record["english_gloss"], card=record["surface_card"],
                       source="https://doi.org/" + record["source_doi"],
                       crosswalk_status=("ASSUMED" if record["crosswalk_kind"] == "assumed" else record["crosswalk_kind"]))
        examples.append(example)
    return {"well": document["basis"]["well"]["value"], "examples": examples,
            "provenance": {"results_path": RESULTS.relative_to(ROOT).as_posix(),
                           "results_sha256": hashlib.sha256(data).hexdigest(),
                           "source": document["source"], "basis": document["basis"],
                           "units": {"position": "in", "load": "lbf"}}}


def script(global_name, body):
    return ("// Generated by build_assets.py; do not hand-edit.\n"
            "(function(root) {\n'use strict';\nconst data = " + body + ";\n"
            f"root.{global_name} = data;\n"
            "if (typeof module === 'object' && module.exports) module.exports = data;\n"
            "}(typeof globalThis !== 'undefined' ? globalThis : this));\n")


def generated_assets():
    examples = build_examples()
    # Compact serialization preserves every parsed model value without pruning.
    models = {}
    for key, filename in (("context", "dynacard_classifier.json"),
                          ("shape", "dynacard_shape_classifier.json")):
        models[key] = json.loads((PACKAGE / "data" / filename).read_text(encoding="utf-8"))
    first = examples["examples"][0]["card"]
    template = ("# position_in (in), load_lbf (lbf); one full stroke; uniformly timed samples; start anywhere\n"
                "position_in,load_lbf\n")
    template += "".join(f"{x!r},{y!r}\n" for x, y in
                        zip(first["position"], first["load"], strict=True))
    return {"models.js": script("DynacardModels", json.dumps(models, separators=(",", ":"),
                                                           ensure_ascii=False, allow_nan=False)),
            "examples.js": script("DynacardExamples", json.dumps(examples, ensure_ascii=False,
                                                                 indent=2, allow_nan=False)),
            "template.csv": template}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for name, content in generated_assets().items():
        target = APP / name
        data = content.encode("utf-8")
        if args.check:
            if not target.exists() or target.read_bytes() != data:
                mismatches.append(name)
        else:
            target.write_bytes(data)
            if target.read_bytes() != data:
                raise OSError(f"Asset readback failed: {name}")
    if mismatches:
        parser.exit(1, "Assets differ: " + ", ".join(mismatches) + "\n")
    print("Assets match source build." if args.check else "Built models.js, examples.js, template.csv.")


if __name__ == "__main__":
    main()
