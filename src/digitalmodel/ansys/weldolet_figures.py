    """One visualisation solve: a declared state, its level and the plots appended."""

    state: str
    level: int
    generator: str
    plots: tuple[tuple[str, str], ...]  # (figure id, APDL lines ending in EPLOT/PLNSOL)
    views: tuple[tuple[str, str], ...]  # (figure id, one-line description of the view)


