# ABOUTME: Visualisation decks for the #2157 weldolet crack models: the exact receipt deck
# ABOUTME: plus an appended MAPDL plotting block; renders host-free PNG figures and a manifest.
"""Model, mesh and result pictures of the #2157 weldolet FE states (P4 Rev B).

Each visualisation deck is the receipt deck of a declared FE state, regenerated by its
generator from the receipt spec and checked against the SHA-256 recorded in the receipt
(fail-closed), followed by a plotting block (``/SHOW,PNG``, ``/VIEW``, ``EPLOT``,
``PLNSOL``). The receipt decks, receipts and their hashes are not changed: the plotting
block exists only in the visualisation deck, which is solved in a scratch directory.

The PNG files are re-encoded without ancillary chunks (no text, time or physical-size
chunk), cropped to the drawing, and listed in ``figures.json`` with their SHA-256, the
state, level, generator and solver release. The report embeds them from that manifest.

Run (licensed host, one job at a time)::

    python -m digitalmodel.ansys.weldolet_figures --work <scratch-dir> \\
        --out examples/workflows/crack-fe-weldolet/figures
"""

