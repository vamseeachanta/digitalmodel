MANIFEST = "figures.json"
_PNG_SIG = b"\x89PNG\r\n\x1a\n"
_KEEP_CHUNKS = (b"IHDR", b"PLTE", b"IDAT", b"IEND")

# crack centre of the crotch flaw at a0 in the symmetry plane (y = 0): x = C/2 + a at the
# deepest point, z = R_o + v0 (v0 = 0.5 - a); used only to aim the views
