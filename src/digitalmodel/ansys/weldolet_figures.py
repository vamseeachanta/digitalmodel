# --------------------------------------------------------------------------- #
# Decks
# --------------------------------------------------------------------------- #
def _receipt(state: str, fe_states: Path) -> dict:
    return json.loads((Path(fe_states) / f"{state}.receipt.json").read_text("utf-8"))


def receipt_deck(state: str, level: int, fe_states: Path) -> str:
    """The receipt deck of ``state`` at ``level``, regenerated and hash-checked."""
    rec = _receipt(state, fe_states)
    if rec["kind"] == "weldolet_uncracked" or "base" not in rec["spec"]:
        deck = wc.generate_weldolet_apdl(wc.spec_from_receipt(rec, level))
    else:
        deck = wcr.generate_crotch_apdl(wcr.spec_from_receipt(rec, level))
    want = next(m["deck_sha256"] for m in rec["meshes"] if m["level"] == level)
    got = wc.deck_sha256(deck)
    if got != want:
        raise ValueError(f"regenerated deck of {state} level {level} does not match the "
                         f"receipt deck digest ({got} != {want})")
    return deck


def visual_deck(run: str, fe_states: Path) -> str:
    """The receipt deck followed by the plotting block of ``run``."""
    spec = RUNS[run]
    body = "".join(lines for _, lines in spec.plots)
    return receipt_deck(spec.state, spec.level, fe_states) + _HEADER + body + "FINISH\n"


# --------------------------------------------------------------------------- #
# PNG hygiene
# --------------------------------------------------------------------------- #
def sanitise_png(blob: bytes) -> bytes:
    """``blob`` with only the critical chunks (IHDR, PLTE, IDAT, IEND) kept."""
    if not blob.startswith(_PNG_SIG):
        raise ValueError("not a PNG file")
    out, pos = [_PNG_SIG], 8
    while pos < len(blob):
        (n,) = struct.unpack(">I", blob[pos:pos + 4])
        kind = blob[pos + 4:pos + 8]
        data = blob[pos + 8:pos + 8 + n]
        if kind in _KEEP_CHUNKS:
            out.append(struct.pack(">I", n) + kind + data
                       + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))
        pos += 12 + n
        if kind == b"IEND":
            break
    return b"".join(out)


def _crop(blob: bytes, margin: int = 16) -> bytes:
    """Crop to the non-white drawing and re-encode (Pillow writes no text chunks)."""
    from PIL import Image, ImageChops

    img = Image.open(io.BytesIO(blob)).convert("RGB")
    bg = Image.new("RGB", img.size, (255, 255, 255))
    box = ImageChops.difference(img, bg).getbbox()
    if box:
        left, t, r, b = box
        img = img.crop((max(left - margin, 0), max(t - margin, 0),
                        min(r + margin, img.width), min(b + margin, img.height)))
    if img.width > 1200:
        img = img.resize((1200, round(img.height * 1200 / img.width)), Image.BOX)
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return sanitise_png(buf.getvalue())


# --------------------------------------------------------------------------- #
# Rendering (licensed host)
# --------------------------------------------------------------------------- #
def render(work: Path, out: Path, fe_states: Path, runs: tuple[str, ...] = tuple(RUNS),
           runner: Callable | None = None) -> dict:
    """Solve each visualisation deck in ``work`` and write the figures to ``out``."""
    from digitalmodel.ansys.runner import ANSYSRunStatus, run_ansys

    runner = runner or run_ansys
    work, out = Path(work), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    man_path = out / MANIFEST
    manifest = (json.loads(man_path.read_text("utf-8")) if man_path.is_file()
                else {"figures": {}})
    manifest["note"] = ("Visualisation decks: the receipt deck of each state (hash-checked) "
                        "plus an appended plotting block; receipts are unchanged.")
    timings = {}
    for name in runs:
        spec = RUNS[name]
        rec = _receipt(spec.state, fe_states)
        rundir = work / name
        if rundir.exists():
            shutil.rmtree(rundir)
        rundir.mkdir(parents=True)
        deck = visual_deck(name, fe_states)
        inp = rundir / f"{spec.state}_L{spec.level}_vis.inp"
        inp.write_bytes(deck.encode("utf-8"))
        t0 = time.monotonic()
        res = runner(inp, output_dir=rundir, timeout_seconds=7200,
                     extra_args=["-smp", "-np", "4"])
        timings[name] = time.monotonic() - t0
        if res.status != ANSYSRunStatus.COMPLETED:
            raise RuntimeError(f"visualisation run {name} failed: {res.error_message}")
        pngs = sorted(rundir.glob("*.png"))
        if len(pngs) != len(spec.plots):
            raise RuntimeError(f"{name}: expected {len(spec.plots)} PNG files, got {len(pngs)}")
        views = dict(spec.views)
        mesh = next(m for m in rec["meshes"] if m["level"] == spec.level)
        for (fid, _), png in zip(spec.plots, pngs):
            blob = _crop(png.read_bytes())
            fname = f"{fid}.png"
            (out / fname).write_bytes(blob)
            manifest["figures"][fid] = {
                "file": fname,
                "sha256": hashlib.sha256(blob).hexdigest(),
                "state": spec.state,
                "level": spec.level,
                "generator": spec.generator,
                "receipt_deck_sha256": mesh["deck_sha256"],
                "mapdl_release": rec["run"]["mapdl_release"],
                "mapdl_version": rec["run"]["mapdl_version"],
                "view": views[fid],
                "width_px": _png_size(blob)[0],
                "height_px": _png_size(blob)[1],
            }
    manifest["figures"] = dict(sorted(manifest["figures"].items()))
    man_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", "utf-8")
    return timings


def _png_size(blob: bytes) -> tuple[int, int]:
    return struct.unpack(">II", blob[16:24])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Render the #2157 weldolet figures (MAPDL).")
    ap.add_argument("--work", required=True, help="scratch directory for the solves")
    ap.add_argument("--out", default="examples/workflows/crack-fe-weldolet/figures")
    ap.add_argument("--fe-states", default="examples/workflows/crack-fe-weldolet/fe_states")
    ap.add_argument("--run", action="append", choices=sorted(RUNS))
    a = ap.parse_args(argv)
    timings = render(Path(a.work), Path(a.out), Path(a.fe_states),
                     tuple(a.run) if a.run else tuple(RUNS))
    for name, sec in timings.items():
        print(f"{name}: {sec:.1f} s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
