"""Read-only audit of retained offline cylinder inputs; no execution capability.

Format source: cylinder_preparation.py, prepare_inputs/_artifacts, and the
2026-09-13 issue-2121-canary-proposal.json cases, basis, criteria and budget.
This checks deterministic input identity, not independent physical correctness.
Call with a quiescent directory: the audit does not lock or snapshot its tree.
"""

import os
import stat
from pathlib import Path

from digitalmodel.ansys.analysis_records import canonical_bytes, digest_bytes
from digitalmodel.ansys.cylinder_benchmark import build_case
from digitalmodel.ansys.cylinder_preparation import (
    PROPOSAL_CANONICAL_SHA256,
    PROPOSAL_GIT_BYTES_SHA256,
    PROPOSAL_GIT_REVISION,
    PROPOSAL_PATH,
    validate_proposal,
)


def _expected(proposal):
    """Reconstruct the saved format from the pinned proposal and current generator."""
    normalized = validate_proposal(proposal)
    # Historical identity fields and schema are copied from prepare_inputs;
    # none establishes present execution or engineering authority.
    provenance = {
        "proposal_path": PROPOSAL_PATH,
        "proposal_git_revision": PROPOSAL_GIT_REVISION,
        "proposal_git_bytes_sha256": PROPOSAL_GIT_BYTES_SHA256,
        "proposal_canonical_sha256": PROPOSAL_CANONICAL_SHA256,
        "numeric_representation": "exact decimal strings; no binary float",
        "authority": "historical source identity only; no approval asserted",
    }
    expected = {
        "proposal.json": canonical_bytes(normalized),
        "basis-criteria.json": canonical_bytes({
            "basis": normalized["basis"],
            "criteria": normalized["criteria"],
            "provenance": provenance,
        }),
    }
    for definition in normalized["cases"]:
        case = build_case(definition["case_id"])
        expected[case["case_id"] + ".inp"] = case["deck_bytes"]
        expected[case["case_id"] + ".json"] = canonical_bytes({
            key: value for key, value in case.items() if key != "deck_bytes"
        })
    files = [
        {"path": name, "bytes": len(raw), "sha256": digest_bytes(raw)}
        for name, raw in expected.items()
    ]
    expected["preparation.json"] = canonical_bytes({
        "schema": "cylinder-offline-preparation-1",
        "status": "prepared_not_executed",
        "case_order": [case["case_id"] for case in normalized["cases"]],
        "provenance": provenance,
        "native_execution": False,
        "independent_reference_established": False,
        "files": files,
    })
    return expected, files, normalized


def _redirected(info):
    return stat.S_ISLNK(info.st_mode) or bool(
        getattr(info, "st_file_attributes", 0)
        & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0)
    )


def _directory(output):
    root = Path(output).absolute()
    if ".." in root.parts:
        raise ValueError("Preparation directory must not contain parent traversal")
    for path in (*reversed(root.parents), root):
        info = path.lstat()
        if _redirected(info) or not stat.S_ISDIR(info.st_mode):
            raise ValueError("Preparation directory is redirected or not a directory")
    return root


def _read_member(path, expected):
    info = path.lstat()
    if _redirected(info) or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError("Preparation member is redirected, shared or nonregular")
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0)
    flags |= getattr(os, "O_BINARY", 0)
    with os.fdopen(os.open(path, flags), "rb") as stream:
        opened = os.fstat(stream.fileno())
        if (not stat.S_ISREG(opened.st_mode) or opened.st_nlink != 1
                or (opened.st_dev, opened.st_ino) != (info.st_dev, info.st_ino)
                or opened.st_size != len(expected)):
            raise ValueError("Preparation member identity or byte count differs")
        # Read bound derives from the regenerated artifact, not a guessed limit.
        raw = stream.read(len(expected) + 1)
    if raw != expected:
        raise ValueError("Preparation member differs from frozen generated bytes")
    return raw


def audit_inputs(output, proposal: dict) -> dict:
    """Verify exact retained input membership, bytes and canonical receipt.

    The required proposal is validated against the existing frozen contract.
    No receipt-supplied path is opened. Each artifact is read once and compared
    against regenerated bytes, so changing its self-declared digest cannot pass.
    Missing, extra, noncanonical or redirected evidence raises ValueError;
    the audit never creates, repairs or removes a file. No numerical tolerance
    is introduced and no execution manifest or approval is produced.
    """
    expected, files, normalized = _expected(proposal)
    try:
        root = _directory(output)
        if {path.name for path in root.iterdir()} != set(expected):
            raise ValueError("Preparation membership differs from frozen input format")
        observed = {name: _read_member(root / name, raw)
                    for name, raw in expected.items()}
        if {path.name for path in root.iterdir()} != set(expected):
            raise ValueError("Preparation membership changed during audit")
    except OSError as error:
        raise ValueError("Preparation inputs are unavailable") from error
    return {
        "status": "VERIFIED_INPUTS_ONLY",
        "case_order": [case["case_id"] for case in normalized["cases"]],
        "files": files,
        "preparation_sha256": digest_bytes(observed["preparation.json"]),
        "native_execution": False,
        "engineering_qualified": False,
        "reference_agreement": "NOT_EVALUATED",
        "execution_readiness": "NOT_EVALUATED",
    }
